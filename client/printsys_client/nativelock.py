"""Один вход в тяжёлую нативную работу на весь процесс.

Зачем это отдельный модуль и почему замок стоит НЕ в интерфейсе.

Страница вызывает Python через `window.pywebview.api.*`, и каждый такой вызов
pywebview выполняет в НОВОМ потоке. Значит, оператор одним кликом может
запустить второй проход по тому же нативному коду, пока первый ещё работает:
печать пакета и печать отдельного документа, предпросмотр во время пакета,
два документа подряд. А нативные библиотеки, которыми мы печатаем, к этому
не готовы:

* pdfium (`pypdfium2`) грузится один раз на процесс и не имеет внутренних
  замков — параллельный вход в `FPDF_*` рушит процесс на месте, без
  исключения Python. Ни `sys.excepthook`, ни `threading.excepthook` такое
  падение не увидят: падает не Python, а нативный код под ним;
* Excel через COM поднимается отдельным экземпляром на каждый вызов и ставит
  ГЛОБАЛЬНЫЙ оконный хук — второй параллельный экземпляр даёт незакрытые
  EXCEL.EXE и мигающие окна.

Флаг «идёт печать» в интерфейсе такой гарантии не даёт: его легко забыть
выставить на одном из путей (так и было — печать отдельного документа и
предпросмотр его не занимали), и он проверяется не атомарно. Поэтому замок
стоит ВНУТРИ самих нативных операций: любой путь, откуда бы он ни пришёл,
сериализуется по построению, а не по дисциплине вызывающего.

Замок реентерабельный: подготовка дела конвертирует документы, а затем тот же
поток печатает — вложенный захват в одном потоке законен.
"""
from __future__ import annotations

import logging
import threading

log = logging.getLogger("printsys.native")

# RLock, а не Lock: один поток заходит сюда вложенно (конвертация → печать)
NATIVE = threading.RLock()


def busy() -> bool:
    """Занят ли нативный участок другим потоком.

    Для подсказки оператору: лучше сразу сказать «идёт печать», чем молча
    держать нажатую кнопку минуту.
    """
    if NATIVE.acquire(blocking=False):
        NATIVE.release()
        return False
    return True
